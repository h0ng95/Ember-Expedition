// The JSON is the editable source. Generated C# also works in headless combat tests.
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'content/localization/messages.json'), 'utf8'));
const keys = new Set();
const quote = x => JSON.stringify(x).replace(/\\u2028/g, '\\u2028').replace(/\\u2029/g, '\\u2029');
const lines = [];
for (const row of source.entries) {
  if (!row.key || keys.has(row.key) || !row.ko || !row.en) throw new Error('Invalid entry: ' + row.key);
  keys.add(row.key);
  const placeholders = s => (s.match(/\{\d+(?:[^{}]*)\}/g) || []).sort().join('|');
  if (placeholders(row.ko) !== placeholders(row.en)) throw new Error('Placeholder mismatch: ' + row.key);
  if (/[가-힣]/.test(row.en)) throw new Error('Untranslated English: ' + row.key);
  lines.push(`            Add(${quote(row.key)}, ${quote(row.ko)}, ${quote(row.en)});`);
}
const output = '// Generated by tools/localization/build.cjs. Edit content/localization/messages.json.\n' +
  'namespace Expedition.Core\n{\n    public static partial class CatalogText\n    {\n' +
  '        static void Populate()\n        {\n' + lines.join('\n') + '\n        }\n    }\n}\n';
const target = path.join(root, 'unity/Assets/Scripts/Core/CatalogText.Data.cs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Regenerate CatalogText.Data.cs');
} else fs.writeFileSync(target, output);
console.log(`Localization: ${keys.size} complete Korean/English entries; generated table ${process.argv.includes('--check') ? 'verified' : 'written'}.`);
